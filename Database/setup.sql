-- Fitness App Database Setup Script for Oracle
-- This script creates the necessary tables and sample data for the fitness tracking application

-- Create Users table
CREATE TABLE USERS (
    USER_ID NUMBER(10) PRIMARY KEY,
    USERNAME VARCHAR2(50) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL UNIQUE,
    FIRST_NAME VARCHAR2(50),
    LAST_NAME VARCHAR2(50),
    PHONE VARCHAR2(15),
    DATE_OF_BIRTH DATE,
    GENDER VARCHAR2(10),
    HEIGHT NUMBER(5,2),
    WEIGHT NUMBER(5,2),
    ACTIVITY_LEVEL VARCHAR2(20),
    CREATED_DATE DATE DEFAULT SYSDATE,
    IS_ACTIVE NUMBER(1) DEFAULT 1
);

-- Create sequence for Users
CREATE SEQUENCE USER_ID_SEQ START WITH 1 INCREMENT BY 1;

-- Create trigger for auto-increment Users
CREATE OR REPLACE TRIGGER USER_ID_TRG
    BEFORE INSERT ON USERS
    FOR EACH ROW
BEGIN
    IF :NEW.USER_ID IS NULL THEN
        :NEW.USER_ID := USER_ID_SEQ.NEXTVAL;
    END IF;
END;
/

-- Create Fitness Plans table
CREATE TABLE FITNESS_PLANS (
    PLAN_ID NUMBER(10) PRIMARY KEY,

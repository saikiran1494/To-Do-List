-- Create a procedure to clean up expired OTPs
CREATE OR REPLACE PROCEDURE CLEANUP_EXPIRED_OTPS
IS
BEGIN
    DELETE FROM OTP_VERIFICATIONS 
    WHERE EXPIRES_AT < SYSDATE AND IS_USED = 0;
    
    COMMIT;
END CLEANUP_EXPIRED_OTPS;
/

-- Create a function to calculate BMI
CREATE OR REPLACE FUNCTION CALCULATE_BMI(p_weight NUMBER, p_height NUMBER)
RETURN NUMBER
IS
    v_bmi NUMBER;
BEGIN
    IF p_weight IS NULL OR p_height IS NULL OR p_height = 0 THEN
        RETURN NULL;
    END IF;
    
    v_bmi := p_weight / POWER((p_height / 100), 2);
    RETURN ROUND(v_bmi, 2);
END CALCULATE_BMI;
